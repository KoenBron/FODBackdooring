from utils.global_settings import FLSettings

def select_clients(round, generator):
    """
    Returns list of clients selected for a round of training. If
    a client schedule is given, the selected clients will be selected
    and the remaining slots will be ranomly generated by generator.
    """
    clients = list(range(FLSettings.TOTAL_CLIENTS))

    if FLSettings.USE_CLIENT_SCHEDULE:
        benign_clients = [c for c in clients if c not in FLSettings.ATTACKER_IDS]
        mal_clients = FLSettings.CLIENT_SCHEDULE.get(round, [])

        return mal_clients + generator.sample(benign_clients, FLSettings.CLIENTS_PER_ROUND - len(mal_clients))

    else:
        # Ordinary random sampling of all clients
        return generator.sample(clients, FLSettings.CLIENTS_PER_ROUND)
